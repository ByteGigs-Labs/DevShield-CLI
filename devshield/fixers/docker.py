from __future__ import annotations

import re
import shlex
from collections.abc import Iterable

from devshield.core.models import Finding, Framework
from devshield.core.parsers import Instruction, effective_user, final_stage, from_parts
from devshield.fixers.base import FixContext, Fixer, appended, line_start
from devshield.fixers.model import Create, Edit, Fix, Skipped

DOCKERIGNORE_BASE = (
    ".git",
    ".gitignore",
    ".dockerignore",
    "Dockerfile*",
    "docker-compose*.yml",
    "docker-compose*.yaml",
    ".env",
    ".env.*",
    "!.env.example",
    "*.log",
    ".idea",
    ".vscode",
    ".DS_Store",
)
DOCKERIGNORE_BY_FRAMEWORK: dict[Framework, tuple[str, ...]] = {
    Framework.NODE: ("node_modules", "npm-debug.log*", "yarn-error.log*", "coverage"),
    Framework.NEXTJS: (".next", "out"),
    Framework.LARAVEL: (
        "vendor",
        "node_modules",
        "storage/logs/*",
        "storage/framework/cache/data/*",
        "storage/framework/sessions/*",
        "storage/framework/views/*",
        "bootstrap/cache/*.php",
    ),
}
NODE_IMAGE = re.compile(r"^(?:[\w.-]+/)*node(?::|@|$)", re.IGNORECASE)
TRAILING = frozenset({"CMD", "ENTRYPOINT", "HEALTHCHECK", "EXPOSE", "LABEL", "STOPSIGNAL"})
PRIVILEGED_PORT = 1024


def _copied(instructions: list[Instruction]) -> list[str]:
    sources: list[str] = []
    for instruction in instructions:
        if instruction.name in {"COPY", "ADD"} and not instruction.args.startswith("["):
            try:
                tokens = [t for t in shlex.split(instruction.args) if not t.startswith("--")]
            except ValueError:
                continue
            sources += [t.strip("./") or "." for t in tokens[:-1]]
    return sources


def _needed(pattern: str, sources: list[str]) -> bool:
    name = pattern.rstrip("/*").strip("./")
    return any(s == name or s.startswith(f"{name}/") for s in sources if name)


class CreateDockerignore(Fixer):
    rule_id = "PERF103"

    def plan(self, fc: FixContext, findings: list[Finding]) -> Iterable[Fix | Skipped]:
        planned: set[str] = set()
        for finding in findings:
            dockerfile = finding.location.file if finding.location else None
            if dockerfile is None:
                continue
            directory = dockerfile.rpartition("/")[0]
            target = f"{directory}/.dockerignore" if directory else ".dockerignore"
            if target in planned:
                continue
            planned.add(target)
            copied = _copied(fc.ctx.dockerfile(dockerfile))
            patterns = list(DOCKERIGNORE_BASE)
            for framework, extra in DOCKERIGNORE_BY_FRAMEWORK.items():
                if fc.ctx.has_framework(framework):
                    patterns += extra
            kept = [
                p for p in dict.fromkeys(patterns) if p.startswith("!") or not _needed(p, copied)
            ]
            content = "# Generated by DevShield\n" + "\n".join(kept) + "\n"
            yield Fix(self.rule_id, f"Create {target}", (Create(target, content),))


class NonRootUser(Fixer):
    rule_id = "PERF102"

    def plan(self, fc: FixContext, findings: list[Finding]) -> Iterable[Fix | Skipped]:
        for finding in findings:
            file = finding.location.file if finding.location else None
            if file is None:
                continue
            instructions = fc.ctx.dockerfile(file)
            stage = final_stage(instructions)
            parts = from_parts(stage[0]) if stage else None
            base = parts[0] if parts else ""
            reason = self._unsafe(instructions, stage, base)
            if reason:
                yield self.skip(reason, finding)
                continue
            text = fc.workspace.read(file) or ""
            newline = fc.workspace.newline(file)
            run = []
            for instruction in reversed(stage[1:]):
                if instruction.name not in TRAILING:
                    break
                run.append(instruction)
            anchor = line_start(text, run[-1].line) if run else None
            if anchor is None:
                yield Fix(
                    self.rule_id,
                    f"Add USER node to {file}",
                    (
                        Edit(
                            file,
                            len(text),
                            len(text),
                            appended(text, f"USER node{newline}", newline),
                        ),
                    ),
                )
            else:
                yield Fix(
                    self.rule_id,
                    f"Add USER node to {file}",
                    (Edit(file, anchor, anchor, f"USER node{newline}"),),
                )

    @staticmethod
    def _unsafe(instructions: list[Instruction], stage: list[Instruction], base: str) -> str | None:
        if not NODE_IMAGE.match(base):
            return "only official node images are fixed automatically (they ship a `node` user)"
        if effective_user(instructions) not in {None, "root", "0"}:
            return "the image already switches user"
        for instruction in stage:
            if instruction.name == "EXPOSE":
                ports = re.findall(r"\d+", instruction.args)
                if any(int(p) < PRIVILEGED_PORT for p in ports):
                    return (
                        "the image listens on a privileged port, which a non-root user cannot bind"
                    )
            if instruction.name == "WORKDIR" and instruction.args.startswith("/root"):
                return "the working directory is inside /root"
        return None
