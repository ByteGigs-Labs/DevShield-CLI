from __future__ import annotations

import html
from pathlib import Path

from devshield.core.models import Finding, ScanResult, Severity
from devshield.core.registry import RuleRegistry
from devshield.reports.sections import group_findings

MAX_ROWS = 50


def _cell(text: str) -> str:
    return html.escape(text, quote=False).replace("|", "\\|").replace("\n", " ")


def _code(text: str) -> str:
    return f"`{text.replace('`', chr(39))}`"


def _row(finding: Finding) -> str:
    location = _code(str(finding.location)) if finding.location else ""
    rule = f"**{finding.rule_id}** {_cell(finding.title)}"
    return f"| {finding.severity.value} | {rule} | {location} | {_cell(finding.message)} |"


def _fixes(findings: list[Finding]) -> list[str]:
    seen: dict[str, str] = {}
    for finding in findings:
        if finding.remediation:
            seen.setdefault(finding.rule_id, finding.remediation)
    return [f"- **{rule_id}**: {_cell(text)}" for rule_id, text in sorted(seen.items())]


def _section(name: str, findings: list[Finding]) -> list[str]:
    opened = " open" if any(f.severity >= Severity.HIGH for f in findings) else ""
    shown = findings[:MAX_ROWS]
    lines = [
        f"<details{opened}>",
        f"<summary><b>{html.escape(name)}</b> ({len(findings)})</summary>",
        "",
        "| Severity | Rule | Location | Message |",
        "|---|---|---|---|",
        *map(_row, shown),
    ]
    if len(findings) > len(shown):
        lines += ["", f"_...and {len(findings) - len(shown)} more. Use the JSON or HTML report._"]
    return [*lines, "", "**How to fix**", "", *_fixes(shown), "", "</details>", ""]


def render_markdown(result: ScanResult, registry: RuleRegistry | None = None) -> str:
    counts = " · ".join(
        f"{result.count(s)} {s.value}" for s in reversed(list(Severity)) if result.count(s)
    )
    lines = [
        "# DevShield report",
        "",
        f"**Project:** {_code(Path(result.root).name)} · "
        f"**Risk score:** {result.score}/100 ({result.band.label}) · "
        f"**Findings:** {len(result.findings)}" + (f" ({counts})" if counts else ""),
        "",
    ]
    for count, reason in (
        (result.suppressed, "suppressed by inline comments"),
        (result.baselined, "hidden by the baseline"),
    ):
        if count:
            lines += [f"_{count} {reason}._", ""]
    if not result.findings:
        lines += ["No issues found.", ""]
    for name, findings in group_findings(result.findings):
        lines += _section(name, findings)
    if result.errors or result.warnings:
        lines += ["## Problems running DevShield", ""]
        lines += [f"- Rule {e.rule_id} failed: {_cell(e.message)}" for e in result.errors]
        lines += [f"- {_cell(w)}" for w in result.warnings]
        lines.append("")
    lines.append(f"_Generated by DevShield {result.devshield_version}._")
    return "\n".join(lines) + "\n"
